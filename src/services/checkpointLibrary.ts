/**
 * 根据日期 + 考试类型 + 板块获取今日考点
 * 使用日期的"年中的第几天"作为种子，确保同一天返回同一条
 */
export function getTodayCheckpoint(date: string, examType: ExamType, subject: SubjectId): string {
  const key = `${examType}_${subject}`;
  const library = CHECKPOINT_LIBRARY[key];

  // 如果该组合没有预置库，返回通用提示
  if (!library || library.length === 0) {
    return `今日${subject}考点：建议复习该板块的核心知识点，可手动编辑添加具体考点内容。`;
  }

  // 用日期作为种子轮换
  const dateObj = new Date(date);
  const dayOfYear = Math.floor(
    (dateObj.getTime() - new Date(dateObj.getFullYear(), 0, 0).getTime()) / 86400000
  );
  const index = dayOfYear % library.length;
  return library[index];
}
